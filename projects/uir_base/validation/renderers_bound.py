"""Development v2: fact-ID enum binding + server-owned request identity.

Stronger reference constraints are explicit, not silently equated with syntax-only
or attributed to shared UIR. The observed development cohort is never a holdout.
"""
import argparse
import json
import time
from jsonschema import validate
from uir_common.ollama_client import OllamaClient
from .common import OUT, ROOT, csvfile, jsonl, load, read, sha, utc, write
from .renderers import PHI, OPTIONS, evaluate


def schema(case):
    return {"type": "object", "additionalProperties": False, "required": ["fact_ids"],
            "properties": {"fact_ids": {"type": "array", "uniqueItems": True, "maxItems": len(case["authorized_catalog"]),
                                       "items": {"type": "string", "enum": list(case["authorized_catalog"])}}}}


def prepare():
    if load(OUT / "renderer_execution_manifest.json")["status"] != "CAPTURE_COMPLETE_DEVELOPMENT":
        raise ValueError("Need preserved v1 results")
    write(OUT / "renderer_bound_protocol.json", {"status": "FROZEN_BEFORE_DEVELOPMENT_V2", "created_at_utc": utc(),
          "condition": "REFERENCE_ENUM_SERVER_BOUND", "N_calls": 272, "model": PHI, "options": OPTIONS, "thinking": False, "retries": 0,
          "source_sha256": sha(__file__), "v1_guard_source_sha256": sha(ROOT / "projects/uir_base/validation/renderers.py"),
          "runtime_sha256": sha(OUT / "renderer_runtime_packets.jsonl"), "v1_raw_sha256": sha(OUT / "renderer_fresh_raw.jsonl"),
          "identity": "trusted synchronous request envelope supplies digest; model does not generate authority/hash metadata",
          "dynamic_enum": "all public authorized catalog IDs, generated before inference; not gold-derived IDs or post-hoc candidate selection",
          "method_difference": "explicitly stronger request-specific reference constraint than generic syntax; no typed-IR causal superiority inference",
          "scope": "same previously inspected oracle-like DEVELOPMENT cohort; no confirmatory or generalization claim"})


def execute():
    protocol = load(OUT / "renderer_bound_protocol.json")
    if sha(__file__) != protocol["source_sha256"] or sha(OUT / "renderer_runtime_packets.jsonl") != protocol["runtime_sha256"]:
        raise ValueError("FROZEN_BOUND_PROTOCOL_CHANGED")
    client = OllamaClient("http://127.0.0.1:18747")
    model, digest = PHI; installed = {r["name"]: r for r in client.get("/api/tags")["models"]}
    if installed.get(model, {}).get("digest") != digest: raise ValueError("ARTIFACT_CHANGED")
    captures = []
    with (OUT / "renderer_bound_raw.jsonl").open("x", encoding="utf-8") as sink:
        for i, case in enumerate(read(OUT / "renderer_runtime_packets.jsonl"), 1):
            request = {"model": model, "messages": [{"role": "system", "content":
                "Enumerate ALL authorized fact IDs, not entity names. Return only JSON {\"fact_ids\":[...]}. "
                "Fact IDs are the keys in authorized_catalog; e.g. F000, F001. No digest, claims, numbers or prose. "
                "Request identity/policy/evidence versioning is owned by the server, not generated by you."},
                {"role": "user", "content": json.dumps({"authorized_catalog": case["authorized_catalog"]}, ensure_ascii=False)}],
                "format": schema(case), "stream": False, "think": False, "keep_alive": "10m", "options": OPTIONS}
            start = time.perf_counter_ns(); wall = time.time_ns()
            response = client.post("/api/chat", request)
            record = {"case_id": case["case_id"], "condition": protocol["condition"], "request": request, "response": response,
                      "server_contract_digest": case["contract_digest"], "model_digest": digest,
                      "duration_ms": (time.perf_counter_ns()-start)/1e6, "start_wall_ns": wall, "end_wall_ns": time.time_ns(),
                      "cold_load_inclusive": i == 1, "retry": 0, "evidence_kind": "fresh_model_inference", "split": "DEVELOPMENT"}
            sink.write(json.dumps(record, ensure_ascii=False, sort_keys=True) + "\n"); sink.flush(); captures.append(record)
            if i % 40 == 0: print("REFERENCE_ENUM_SERVER_BOUND", i, "/272", flush=True)
    allocation = client.get("/api/ps")
    if not any(r["name"] == model and r.get("size_vram", 0) > 0 for r in allocation["models"]): raise ValueError("GPU_NOT_CONFIRMED")
    write(OUT / "renderer_bound_manifest.json", {"status": "CAPTURE_COMPLETE_DEVELOPMENT_V2", "created_at_utc": utc(), "N_calls": len(captures),
          "raw_sha256": sha(OUT / "renderer_bound_raw.jsonl"), "protocol_sha256": sha(OUT / "renderer_bound_protocol.json"),
          "artifact": installed[model], "allocation": allocation, "server": client.get("/api/version"),
          "show": client.post("/api/show", {"model": model}), "remote_inference": False})
    client.post("/api/generate", {"model": model, "keep_alive": 0})


def score():
    cases = {r["case_id"]: r for r in read(OUT / "renderer_runtime_packets.jsonl")}
    records = read(OUT / "renderer_bound_raw.jsonl")
    manifest = load(OUT / "renderer_bound_manifest.json")
    if sha(OUT / "renderer_bound_raw.jsonl") != manifest["raw_sha256"] or len({r["case_id"] for r in records}) != 272:
        raise ValueError("BOUND_CAPTURE_INTEGRITY_FAIL")
    scores = []
    for record in records:
        response = record["response"]; case = cases[record["case_id"]]; error = None; candidate = ""
        try:
            body = json.loads(response["message"]["content"]); validate(body, schema(case))
            # This is a trusted transport binding, never an unchecked model-supplied digest.
            candidate = json.dumps({"contract_digest": record["server_contract_digest"], "fact_ids": body["fact_ids"]})
        except Exception as exc: error = type(exc).__name__
        result = evaluate(candidate, case, "FACT_ID_BINDING", finished=response.get("done_reason") == "stop" and response.get("done") is True)
        scores.append({"case_id": case["case_id"], "condition": "REFERENCE_ENUM_SERVER_BOUND", "finish_reason": response.get("done_reason", "MISSING"),
            "format_error": error, "complete": result["complete"], "partial": result["partial"], "accepted_nonempty": result["accepted_nonempty"],
            "structured_unsupported": result["structured_unsupported"], "errors": result["errors"], "evidence_kind": "fresh_model_inference",
            "scope": "DEVELOPMENT, stronger binding constraint, not representation superiority", "native_prose_AUCR": "NOT_MEASURED"})
    csvfile(OUT / "renderer_bound_results.csv", scores)
    write(OUT / "renderer_bound_summary.json", {"N": len(scores), "N_complete": sum(r["complete"] for r in scores),
          "N_partial": sum(r["partial"] for r in scores), "N_nonempty": sum(r["accepted_nonempty"] for r in scores),
          "N_unsupported": sum(r["structured_unsupported"] for r in scores), "N_model_calls": len(scores),
          "native_prose_AUCR": "NOT_MEASURED", "development_version": 2, "dynamic_reference_enum": True, "server_bound_identity": True})


if __name__ == "__main__":
    parser = argparse.ArgumentParser(); parser.add_argument("--prepare", action="store_true"); parser.add_argument("--execute", action="store_true"); parser.add_argument("--score", action="store_true")
    args = parser.parse_args()
    if args.prepare: prepare()
    elif args.execute: execute()
    elif args.score: score()
    else: parser.error("Explicit --prepare / --execute / --score")
